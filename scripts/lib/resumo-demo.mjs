// Gera a página de resumo da demonstração de uma etapa (milestone):
// capturas de tela dos cenários + o que entrou e o que ficou para depois, vindos do GitHub.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const API_GITHUB = "https://api.github.com";

/** `owner/repo` a partir do campo `repository` do package.json da raiz. */
export function repositorioDoPacote(raiz) {
  const pacote = JSON.parse(readFileSync(join(raiz, "package.json"), "utf8"));
  const url = typeof pacote.repository === "string" ? pacote.repository : pacote.repository?.url;
  const m = url?.match(/github\.com[/:]([^/]+\/[^/.]+)/);
  if (!m) throw new Error("package.json sem o campo repository apontando para o GitHub.");
  return m[1];
}

async function github(caminho) {
  const cabecalhos = { Accept: "application/vnd.github+json", "User-Agent": "voxa-demo" };
  // biome-ignore lint/suspicious/noUndeclaredEnvVars: o pnpm demo roda fora do Turborepo; sem cache a invalidar.
  if (process.env.GITHUB_TOKEN) cabecalhos.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const res = await fetch(`${API_GITHUB}${caminho}`, { headers: cabecalhos });
  if (!res.ok) throw new Error(`GitHub respondeu ${res.status} para ${caminho}`);
  return res.json();
}

/** Número do milestone aberto mais antigo (a etapa atual), ou `undefined` se não der para consultar. */
export async function milestoneAtual(repo) {
  try {
    const abertos = await github(`/repos/${repo}/milestones?state=open&per_page=100`);
    return abertos.map((m) => m.number).sort((a, b) => a - b)[0];
  } catch {
    return undefined;
  }
}

/** Dados do milestone: título, descrição, issues e PRs. `undefined` se o GitHub estiver fora de alcance. */
async function dadosDoMilestone(repo, numero) {
  try {
    const [milestone, itens] = await Promise.all([
      github(`/repos/${repo}/milestones/${numero}`),
      github(`/repos/${repo}/issues?milestone=${numero}&state=all&per_page=100`),
    ]);
    const issues = itens.filter((i) => !i.pull_request);
    const prs = itens.filter((i) => i.pull_request);
    return { milestone, issues, prs };
  } catch (erro) {
    return { erro: erro.message };
  }
}

export function lerCapturas(pasta) {
  const arquivo = join(pasta, "capturas.jsonl");
  if (!existsSync(arquivo)) return [];
  return readFileSync(arquivo, "utf8")
    .split("\n")
    .filter(Boolean)
    .map((linha) => JSON.parse(linha));
}

export function escapar(texto) {
  return String(texto ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function itemDeLista(item) {
  return `<li><a href="${escapar(item.html_url)}">#${item.number}</a> ${escapar(item.title)}</li>`;
}

function lista(itens, vazio) {
  if (itens.length === 0) return `<p class="suave">${escapar(vazio)}</p>`;
  return `<ul>${itens.map(itemDeLista).join("")}</ul>`;
}

/**
 * Monta o HTML da página de resumo. Puro (sem rede nem disco), para ser testado.
 * As imagens vão embutidas (data URI): a página é um arquivo só, fácil de abrir e compartilhar.
 */
export function montarHtml({ repo, numero, dados, capturas, imagens, testesOk, commit, geradoEm }) {
  const titulo = dados?.milestone?.title ?? `Milestone ${numero}`;
  // Sem o rodapé de atribuição que ferramentas de automação acrescentam às descrições.
  const descricao = (dados?.milestone?.description ?? "").replace(
    /\s*---\s*_Generated by[^\n]*_\s*$/,
    "",
  );
  const entregues = (dados?.issues ?? []).filter((i) => i.state === "closed");
  const pendentes = (dados?.issues ?? []).filter((i) => i.state === "open");
  const mergeados = (dados?.prs ?? []).filter((p) => p.pull_request?.merged_at);

  const figuras = capturas
    .map(
      (c) => `
      <figure>
        <img src="${imagens[c.arquivo] ?? escapar(c.arquivo)}" alt="${escapar(c.titulo)}" loading="lazy">
        <figcaption><strong>${escapar(c.titulo)}</strong> ${escapar(c.descricao)}</figcaption>
      </figure>`,
    )
    .join("");

  const situacao = testesOk
    ? `<span class="selo ok">✓ Todos os cenários passaram</span>`
    : `<span class="selo erro">✕ Algum cenário falhou: veja o log do <code>pnpm demo</code></span>`;

  const github = dados?.erro
    ? `<p class="suave">Não foi possível consultar o GitHub (${escapar(dados.erro)}). As capturas abaixo continuam valendo.</p>`
    : `
      <section>
        <h2>O que entrou</h2>
        ${lista(entregues, "Nenhuma issue fechada ainda.")}
        <h3>Pull requests mergeados</h3>
        ${lista(mergeados, "Nenhum PR mergeado ainda.")}
      </section>
      <section>
        <h2>O que ficou para depois</h2>
        ${lista(pendentes, "Nada: todas as issues da etapa foram fechadas.")}
      </section>`;

  return `<!doctype html>
<html lang="pt-BR">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Voxa · Demonstração · ${escapar(titulo)}</title>
<style>
  :root { color-scheme: light dark; --fundo: #f6f7f9; --cartao: #fff; --texto: #1d2129; --suave: #5b6472; --borda: #d9dde3; --ok: #116329; --ok-fundo: #e3f5e8; --erro: #a1161c; --erro-fundo: #fde7e7; }
  @media (prefers-color-scheme: dark) { :root { --fundo: #14171c; --cartao: #1c2027; --texto: #e6e8eb; --suave: #a3abb7; --borda: #343a44; --ok: #7ee2a0; --ok-fundo: #12331f; --erro: #ff9b9b; --erro-fundo: #3d1717; } }
  body { margin: 0; background: var(--fundo); color: var(--texto); font: 16px/1.5 system-ui, sans-serif; }
  main { max-width: 60rem; margin: 0 auto; padding: 2rem 1rem 4rem; }
  h1 { margin: 0 0 .25rem; font-size: 1.75rem; }
  .suave { color: var(--suave); }
  .selo { display: inline-block; padding: .2rem .6rem; border-radius: 1rem; font-weight: 600; }
  .ok { background: var(--ok-fundo); color: var(--ok); }
  .erro { background: var(--erro-fundo); color: var(--erro); }
  section { background: var(--cartao); border: 1px solid var(--borda); border-radius: .75rem; padding: 1rem 1.25rem; margin-top: 1.25rem; }
  figure { margin: 1rem 0 1.75rem; }
  figure img { width: 100%; height: auto; border: 1px solid var(--borda); border-radius: .5rem; }
  figcaption { margin-top: .5rem; }
  a { color: inherit; }
  code { font-size: .9em; }
</style>
</head>
<body>
<main>
  <p class="suave">Voxa · Demonstração da etapa</p>
  <h1>${escapar(titulo)}</h1>
  ${descricao ? `<p>${escapar(descricao)}</p>` : ""}
  <p>${situacao}</p>
  <p class="suave">Gerada em ${escapar(geradoEm)} a partir do commit <code>${escapar(commit)}</code> de
    <a href="https://github.com/${escapar(repo)}">${escapar(repo)}</a>.</p>
  <section>
    <h2>Capturas de tela</h2>
    ${figuras || '<p class="suave">Nenhuma captura registrada.</p>'}
  </section>
  ${github}
</main>
</body>
</html>
`;
}

/** Gera `index.html` na pasta da demonstração e devolve o caminho. */
export async function gerarResumo({ pasta, repo, numero, testesOk, commit }) {
  const capturas = lerCapturas(pasta);
  const imagens = {};
  for (const c of capturas) {
    const caminho = join(pasta, c.arquivo);
    if (existsSync(caminho)) {
      imagens[c.arquivo] = `data:image/png;base64,${readFileSync(caminho).toString("base64")}`;
    }
  }
  const dados = await dadosDoMilestone(repo, numero);
  const html = montarHtml({
    repo,
    numero,
    dados,
    capturas,
    imagens,
    testesOk,
    commit,
    geradoEm: new Date().toLocaleString("pt-BR", { timeZone: "America/Sao_Paulo" }),
  });
  const saida = join(pasta, "index.html");
  writeFileSync(saida, html);
  return saida;
}
